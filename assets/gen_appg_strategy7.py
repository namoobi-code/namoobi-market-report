def card(tk, nm, bt, bk, mo):
    b = f'<span class="{bk}">{bt or "비상장"}</span>' if bk else ""
    nm2 = f'<span class="nm">{nm}</span>' if nm and nm != "비상장" else ('<span class="nm">비상장</span>' if nm == "비상장" else "")
    return (f'<div class="card">{b}<span class="tk">{tk}</span>'
            f'{nm2}<div class="mo">{mo}</div></div>')

def block_html(b):
    kind = b[0]
    if kind == "hdr":
        return f'<div class="hd"><span class="t">{b[1]}</span><span class="s">{b[2]}</span></div>'
    if kind == "sec":
        cards = "".join(card(*r) for r in b[3])
        return (f'<div class="sec"><div class="sh"><span class="t">{b[1]}</span>'
                f'<span class="s">{b[2]}</span></div><div class="cards">{cards}</div></div>')
    if kind == "arr":
        return f'<div class="arr">▼&nbsp;&nbsp;{b[1]}</div>'
    if kind == "cyc":
        return f'<div class="cyc">{b[1]}</div>'
    return ""

